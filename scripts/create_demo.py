def other(out):
    w=Workbook();s=w.active;s.title="Synthetic data"
    for row in [("Category","Example value"),("Group A",4),("Group B",7),("Group C",9),("TOTAL",None)]:s.append(row)
    s["B5"]="=SUM(B2:B4)"
    for cell in s[1]:cell.fill=PatternFill("solid",fgColor="227E84");cell.font=Font(color="FFFFFF",bold=True)
    s.column_dimensions["A"].width=24;s.column_dimensions["B"].width=22
    ch=BarChart();ch.title="Synthetic group values";ch.add_data(Reference(s,min_col=2,min_row=1,max_row=4),titles_from_data=True)
    ch.set_categories(Reference(s,min_col=1,min_row=2,max_row=4));s.add_chart(ch,"D2")
    w.save(out/"synthetic_example.xlsx")
    d=Document();d.add_heading("Research briefing — example",0)
    d.add_paragraph("This editable Word document uses synthetic examples only.")
    d.add_heading("What remains to validate",level=1)
    d.add_paragraph("Source accuracy, independent evidence, meaningful figures and visual document quality.")
    d.save(out/"synthetic_example.docx")
    c=Canvas(str(out/"synthetic_example.pdf"),pagesize=(595,842))
    c.setTitle("Synthetic research briefing")
    c.setFont("Helvetica-Bold",22);c.drawString(48,770,"Research briefing - example")
    c.setFont("Helvetica",12);c.drawString(48,735,"Synthetic content only. No external factual claims.")
    c.line(48,706,548,706)
    c.drawString(48,670,"Source and visual review are separate required steps.")
    c.showPage();c.save()
def main():
    a=argparse.ArgumentParser();a.add_argument("--out",default="artifacts/demo");o=a.parse_args()
    out=Path(o.out);out.mkdir(parents=True,exist_ok=True)
    for name,fn in [("executive",executive),("brand",brand),("research",research)]:
        p=deck();fn(p);p.save(out/(name+"_synthetic.pptx"))
    other(out)
    print("Generated three visually differentiated, editable synthetic PPTX decks and XLSX/PDF/DOCX in",out)
    print("Visual rendering, factual claims and font substitution are NOT certified by this generator.")
if __name__=="__main__":main()
