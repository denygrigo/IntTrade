def rgb(s):return RGBColor.from_string(s.strip("#"))
def deck():
    p=Presentation();p.slide_width=Inches(13.333);p.slide_height=Inches(7.5);return p
def slide(p):return p.slides.add_slide(p.slide_layouts[6])
def box(s,x,y,w,h,color):
    q=s.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
    q.fill.solid();q.fill.fore_color.rgb=rgb(color);q.line.fill.background();return q
def txt(s,x,y,w,h,words,size,color,bold=False,font="Aptos"):
    shape=s.shapes.add_textbox(Inches(x),Inches(y),Inches(w),Inches(h))
    frame=shape.text_frame;frame.word_wrap=True
    p=frame.paragraphs[0];p.text=words;p.font.name=font;p.font.size=Pt(size)
    p.font.bold=bold;p.font.color.rgb=rgb(color)
    return shape
